//! `sqlparser_derive` 0.5.0 reads `src/dialect/mod.rs` of the crate that invokes
//! `derive_dialect!`. That file is the sqlparser `Dialect` trait, not a module
//! of this crate. Copy the locked sqlparser trait there so the macro can see it.

use std::{
    fs,
    path::{Path, PathBuf},
};

fn main() {
    let manifest_dir =
        PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let version = locked_sqlparser_version(&manifest_dir);
    let source = find_sqlparser_dialect_mod(&version);
    println!("cargo:rerun-if-changed={}", source.display());
    println!("cargo:rerun-if-changed=build.rs");

    let text = fs::read_to_string(&source)
        .unwrap_or_else(|error| panic!("read {}: {error}", source.display()));
    let trait_src = extract_dialect_trait(&text);
    let snapshot = format!(
        "// Generated by build.rs from sqlparser {version} Dialect trait.\n// derive_dialect! \
         (sqlparser_derive 0.5.0) reads this path. Not a Rust module.\n{trait_src}\n"
    );

    let dest_dir = manifest_dir.join("src/dialect");
    fs::create_dir_all(&dest_dir)
        .unwrap_or_else(|error| panic!("create {}: {error}", dest_dir.display()));
    let dest = dest_dir.join("mod.rs");
    if fs::read_to_string(&dest).ok().as_deref() != Some(snapshot.as_str()) {
        fs::write(&dest, snapshot)
            .unwrap_or_else(|error| panic!("write {}: {error}", dest.display()));
    }
}

fn locked_sqlparser_version(manifest_dir: &Path) -> String {
    let mut dir = manifest_dir.to_path_buf();
    loop {
        let lock = dir.join("Cargo.lock");
        if lock.is_file() {
            let text = fs::read_to_string(&lock)
                .unwrap_or_else(|error| panic!("read {}: {error}", lock.display()));
            return sqlparser_version_from_lock(&text);
        }
        if !dir.pop() {
            panic!("Cargo.lock not found from {}", manifest_dir.display());
        }
    }
}

fn sqlparser_version_from_lock(text: &str) -> String {
    let mut name_is_sqlparser = false;
    for line in text.lines() {
        let trimmed = line.trim();
        if trimmed == "[[package]]" {
            name_is_sqlparser = false;
            continue;
        }
        if trimmed == "name = \"sqlparser\"" {
            name_is_sqlparser = true;
            continue;
        }
        if name_is_sqlparser {
            if let Some(version) = trimmed.strip_prefix("version = \"") {
                let version = version.trim_end_matches('"');
                if !version.is_empty() {
                    return version.to_string();
                }
            }
        }
    }
    panic!("sqlparser version not found in Cargo.lock");
}

fn find_sqlparser_dialect_mod(version: &str) -> PathBuf {
    let mut homes = Vec::new();
    if let Some(home) = std::env::var_os("CARGO_HOME") {
        homes.push(PathBuf::from(home));
    }
    if let Some(home) = std::env::var_os("HOME") {
        homes.push(PathBuf::from(home).join(".cargo"));
    }
    let file_name = format!("sqlparser-{version}");
    for home in homes {
        let registry = home.join("registry/src");
        let Ok(indexes) = fs::read_dir(&registry) else {
            continue;
        };
        for index in indexes.flatten() {
            let candidate = index.path().join(&file_name).join("src/dialect/mod.rs");
            if candidate.is_file() {
                return candidate;
            }
        }
    }
    panic!(
        "sqlparser {version} dialect/mod.rs not found under CARGO_HOME or ~/.cargo/registry/src"
    );
}

fn extract_dialect_trait(source: &str) -> String {
    let start = source
        .find("pub trait Dialect")
        .expect("Dialect trait missing from sqlparser dialect/mod.rs");
    let mut depth = 0_i32;
    let mut started = false;
    for (offset, ch) in source[start..].char_indices() {
        match ch {
            '{' => {
                depth += 1;
                started = true;
            },
            '}' => {
                depth -= 1;
                if started && depth == 0 {
                    return source[start..start + offset + 1].to_string();
                }
            },
            _ => {},
        }
    }
    panic!("Dialect trait is missing its closing brace");
}
